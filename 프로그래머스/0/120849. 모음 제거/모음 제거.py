def solution(my_string):
    answer = ""
    for i in my_string:
        if i == 'a':
            answer += ''
        elif i == 'e':
            answer += ''
        elif i == 'i':
            answer += ''    
        elif i == 'o':
            answer += ''    
        elif i== 'u':
            answer += ''
        else:
            answer += i
    return answer